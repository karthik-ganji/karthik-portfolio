CREATE POLICY "Allow public read access on skills" ON public.skills FOR SELECT USING (true);
CREATE POLICY "Allow public read access on projects" ON public.projects FOR SELECT USING (true);
CREATE POLICY "Allow public read access on experience" ON public.experience FOR SELECT USING (true);
CREATE POLICY "Allow public read access on education" ON public.education FOR SELECT USING (true);
CREATE POLICY "Allow public read access on achievements" ON public.achievements FOR SELECT USING (true);
CREATE POLICY "Allow public read access on settings" ON public.settings FOR SELECT USING (true);

-- Admin write access policies
CREATE POLICY "Allow admin write access on profiles" ON public.profiles FOR ALL USING (public.is_admin());
CREATE POLICY "Allow admin write access on skills" ON public.skills FOR ALL USING (public.is_admin());
CREATE POLICY "Allow admin write access on projects" ON public.projects FOR ALL USING (public.is_admin());
CREATE POLICY "Allow admin write access on experience" ON public.experience FOR ALL USING (public.is_admin());
CREATE POLICY "Allow admin write access on education" ON public.education FOR ALL USING (public.is_admin());
CREATE POLICY "Allow admin write access on achievements" ON public.achievements FOR ALL USING (public.is_admin());
CREATE POLICY "Allow admin write access on settings" ON public.settings FOR ALL USING (public.is_admin());

-- Contact messages policies
CREATE POLICY "Allow public anonymous insertion on messages" ON public.messages FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow admin view and delete on messages" ON public.messages FOR ALL USING (public.is_admin());

